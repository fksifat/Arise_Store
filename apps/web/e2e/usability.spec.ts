import { test, expect } from '@playwright/test';
import { storefrontThemes } from '../src/lib/storefront-themes';
const runId = process.env.E2E_RUN_ID || Date.now().toString();

test('merchant edits and customer browsing work across all themes on desktop and mobile', async ({ page, baseURL }) => {
  test.setTimeout(90000);
  const origin = new URL(baseURL!).origin;
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.route('https://example.com/**', route => route.abort());
  const post = async (path: string, data: any) => {
    const response = await page.request.post(`/api/v1${path}`, {headers:{Origin:origin},data});
    expect(response.ok(), await response.text()).toBe(true); return response.json();
  };
  const patch = async (path: string, data: any) => {
    const response = await page.request.patch(`/api/v1${path}`, {headers:{Origin:origin},data});
    expect(response.ok(), await response.text()).toBe(true); return response.json();
  };
  await post('/auth/register',{name:'Usability Merchant',email:`e2e-${runId}-usability@example.com`,password:'Browser-test-password-123'});
  const shop = await post('/shops',{name:'Usability Store',slug:`usability-${runId}`});
  const shirts = await post(`/shops/${shop.id}/categories`,{name:'Shirts'});
  const accessories = await post(`/shops/${shop.id}/categories`,{name:'Accessories'});
  await post(`/shops/${shop.id}/categories`,{name:'Empty category'});
  const product = await post(`/shops/${shop.id}/products`,{name:'Blue Shirt',sku:'BLUE-001',description:'Original description',price_minor:125000,compare_at_price_minor:150000,stock_quantity:5,status:'draft',category_ids:[shirts.id,accessories.id],images:[{image_url:'https://example.com/old.jpg',alt_text:'Front view',is_primary:true},{image_url:'https://example.com/detail.jpg',sort_order:1}]});
  await post(`/shops/${shop.id}/products`,{name:'Travel Bag',sku:'BAG-001',price_minor:50000,stock_quantity:3,category_ids:[accessories.id]});

  await page.goto('/dashboard/products');
  await page.getByPlaceholder('Search products by name or SKU...').fill('blue-001');
  await expect(page.getByText('Blue Shirt',{exact:true})).toBeVisible();
  await expect(page.getByText('Travel Bag',{exact:true})).not.toBeVisible();
  await page.getByRole('button',{name:'Edit Blue Shirt',exact:true}).click();
  const editor = page.getByRole('dialog',{name:'Edit Product',exact:true});
  await expect(editor.getByRole('checkbox',{name:'Shirts',exact:true})).toBeChecked();
  await expect(editor.getByRole('checkbox',{name:'Accessories',exact:true})).toBeChecked();
  await patch(`/shops/${shop.id}/products/${product.id}`,{stock_quantity:3});
  await editor.getByLabel('Product Name').fill('Updated Blue Shirt');
  await editor.getByLabel('Selling Price (BDT)').fill('0.29');
  await editor.getByLabel('Compare-at Price (Optional)').fill('');
  await editor.getByLabel('SKU Code').fill('');
  await editor.getByLabel('Description').fill('');
  await editor.getByLabel('Product Image URL').fill('https://example.com/new.jpg');
  const saveRequest = page.waitForRequest(request => request.method() === 'PATCH' && request.url().endsWith(`/products/${product.id}`));
  await editor.getByRole('button',{name:'Save Product',exact:true}).click();
  const submitted = (await saveRequest).postDataJSON();
  expect(submitted).not.toHaveProperty('stock_quantity');
  expect(submitted).not.toHaveProperty('category_ids');
  await expect(editor).not.toBeVisible();
  const saved = await (await page.request.get(`/api/v1/shops/${shop.id}/products/${product.id}`)).json();
  expect(saved.price_minor).toBe(29); expect(saved.stock_quantity).toBe(3); expect(saved.status).toBe('draft');
  expect(saved.sku).toBeNull(); expect(saved.compare_at_price_minor).toBeNull(); expect(saved.description).toBeNull();
  expect(saved.category_ids.sort()).toEqual([shirts.id,accessories.id].sort());
  expect(saved.images.map((image: any) => image.image_url)).toEqual(['https://example.com/new.jpg','https://example.com/detail.jpg']);
  expect(saved.images[0].alt_text).toBe('Front view');
  await page.getByRole('button',{name:'Add New Product',exact:true}).click();
  await expect(page.getByRole('dialog').getByLabel('Product Name')).toHaveValue('');
  await page.getByRole('dialog').getByRole('button',{name:'Cancel',exact:true}).click();
  await patch(`/shops/${shop.id}/products/${product.id}`,{status:'active',price_minor:200000});
  await post(`/shops/${shop.id}/publish`,{});

  for (const theme of storefrontThemes.map(theme => theme.key)) await test.step(theme, async () => {
    expect((await page.request.put(`/api/v1/shops/${shop.id}/theme-settings`,{headers:{Origin:origin},data:{theme_key:theme,settings_json:{}}})).ok()).toBe(true);
    await page.setViewportSize({width:1440,height:1000});
    await page.goto(`/store/${shop.slug}`);
    await expect(page.getByRole('heading',{name:'Updated Blue Shirt',exact:true})).toBeVisible();
    await expect(page.getByRole('img',{name:'Updated Blue Shirt (image unavailable)',exact:true})).toBeVisible();
    await expect(page.getByRole('img',{name:'Travel Bag (image unavailable)',exact:true})).toBeVisible();
    await page.getByRole('group',{name:'Product categories'}).getByRole('button',{name:'Shirts',exact:true}).click();
    await expect(page.getByRole('heading',{name:'Travel Bag',exact:true})).not.toBeVisible();
    await expect(page.getByRole('group',{name:'Product categories'}).getByRole('button',{name:'Shirts',exact:true})).toHaveAttribute('aria-pressed','true');
    await page.getByLabel('Search products').fill('missing-product');
    await expect(page.getByText('No products match your filters.',{exact:true})).toBeVisible();
    await page.getByRole('button',{name:'Clear filters',exact:true}).click();
    await page.getByLabel('Search products').fill('bag-001');
    await expect(page.getByRole('heading',{name:'Travel Bag',exact:true})).toBeVisible();
    await expect(page.getByRole('heading',{name:'Updated Blue Shirt',exact:true})).not.toBeVisible();
    await page.getByLabel('Search products').fill('');
    await page.getByLabel('Sort by').selectOption('price_asc');
    await expect(page.locator('main h3')).toHaveText(['Travel Bag','Updated Blue Shirt']);
    await page.getByLabel('Sort by').selectOption('price_desc');
    await expect(page.locator('main h3')).toHaveText(['Updated Blue Shirt','Travel Bag']);
    await page.setViewportSize({width:390,height:844});
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
    await expect(page.getByRole('link',{name:'Track an order',exact:true})).toBeVisible();
    await page.getByRole('group',{name:'Product categories'}).getByRole('button',{name:'Empty category',exact:true}).click();
    await expect(page.getByText('No products match your filters.',{exact:true})).toBeVisible();
    await page.getByRole('button',{name:'Clear filters',exact:true}).click();
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({path:`/tmp/arise-${theme}-after.png`,fullPage:true});
    await page.getByRole('link',{name:'Track an order',exact:true}).click();
    await expect(page.getByRole('heading',{name:'Track Your Order',exact:true})).toBeVisible();
    await page.getByRole('link',{name:'Back to store',exact:true}).click();
  });
  expect(errors).toEqual([]);
});
